# gen_benchmarks.py — render BENCHMARKS.md from the per-system baseline matrices.
#
# Aggregates every `benchmarks/results/<arch>-baseline-matrix/` directory (each
# produced by scripts/baseline_matrix.py on one machine) into a single
# cross-system benchmark document. To add a system, run the matrix driver on it
# and commit its `<arch>-baseline-matrix/` dir — this generator picks it up.
#
# Usage: scripts/gen_benchmarks.py [--out BENCHMARKS.md]
#
# Tooling only (allowed per AGENTS.md: no Python in the inference hot path).
from __future__ import annotations
import argparse, glob, json, os
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MATRIX_GLOB = "benchmarks/results/*-baseline-matrix"
FORMATS = ["mq4", "oq4", "mq4+", "oq4+", "oq4++"]   # column order
CANONICAL_KV = "q8"                                  # KV mode used for the pivots


def load_systems() -> list[dict]:
    systems = []
    for d in sorted(glob.glob(str(REPO / MATRIX_GLOB))):
        d = Path(d)
        jl = d / "result-data.jsonl"
        if not jl.exists():
            continue
        name = d.name[: -len("-baseline-matrix")]
        meta = {}
        sj = d / "system.json"
        if sj.exists():
            try:
                meta = json.loads(sj.read_text())
            except Exception:
                meta = {}
        rows = [json.loads(l) for l in jl.read_text().splitlines() if l.strip()]
        systems.append({"name": name, "meta": meta, "rows": rows, "dir": d})
    return systems


def model_order(rows: list[dict]) -> list[str]:
    seen = []
    for r in rows:
        if r["model"] not in seen:
            seen.append(r["model"])
    return seen


def pivot(rows: list[dict], metric: str, kv: str) -> dict[tuple[str, str], float]:
    """(model, format) -> metric value for ok cells at the given KV mode."""
    out = {}
    for r in rows:
        if r.get("status") == "ok" and r.get("kv") == kv and r.get(metric) is not None:
            out[(r["model"], r["format"])] = r[metric]
    return out


def fmt_table(rows: list[dict], metric: str, kv: str) -> str:
    p = pivot(rows, metric, kv)
    models = model_order(rows)
    hdr = "| Model | " + " | ".join(FORMATS) + " |\n"
    hdr += "|---|" + "--:|" * len(FORMATS) + "\n"
    lines = []
    for m in models:
        cells = []
        for f in FORMATS:
            v = p.get((m, f))
            cells.append("" if v is None else f"{v:.0f}")
        if any(cells):
            lines.append(f"| {m} | " + " | ".join(cells) + " |")
    return hdr + "\n".join(lines) if lines else "_no working cells_\n"


def kv_coverage(rows: list[dict]) -> str:
    """Which KV modes load (any ok cell), per KV mode."""
    kvs = {}
    for r in rows:
        kvs.setdefault(r["kv"], {"ok": 0, "fail": 0})
        kvs[r["kv"]]["ok" if r.get("status") == "ok" else "fail"] += 1
    order = ["q8", "asym4", "f16", "kvarn"]
    parts = []
    for kv in order:
        if kv in kvs:
            c = kvs[kv]
            parts.append(f"`{kv}` {c['ok']}✓/{c['fail']}✗")
    return ", ".join(parts)


def system_label(s: dict) -> str:
    meta = s["meta"]
    bucket = meta.get("hardware_bucket")
    extra = f" — `{bucket}`" if bucket else ""
    if meta.get("rocm"):
        extra += f", ROCm {meta['rocm']}"
    return f"{s['name']}{extra}"


def render(systems: list[dict]) -> str:
    out = ["# hipfire Benchmarks\n",
           "_Auto-generated by `scripts/gen_benchmarks.py` from "
           "`benchmarks/results/*-baseline-matrix/`. Do not edit by hand._\n",
           "Speed is the `hipfire eval` speed battery (prefill / decode tok/s, fast tier). "
           "Quality is mean KLD vs a q8f16 reference where a calibration sidecar was available. "
           "Each system runs `scripts/baseline_matrix.py` and commits its own "
           "`<arch>-baseline-matrix/` directory; this doc aggregates them.\n"]

    if not systems:
        out.append("_No `*-baseline-matrix/` results found yet._\n")
        return "\n".join(out)

    # Systems overview
    out.append("## Systems\n")
    out.append("| System | Models | Working cells | Formats benched |")
    out.append("|---|---:|---:|---|")
    for s in systems:
        rows = s["rows"]
        nmodels = len({r["model"] for r in rows})
        nok = sum(1 for r in rows if r.get("status") == "ok")
        fmts = sorted({r["format"] for r in rows}, key=lambda f: FORMATS.index(f) if f in FORMATS else 99)
        out.append(f"| {system_label(s)} | {nmodels} | {nok} | {', '.join(fmts)} |")
    out.append("")

    # Per-system detail
    for s in systems:
        rows = s["rows"]
        out.append(f"## {s['name']}\n")
        out.append(f"KV-mode coverage: {kv_coverage(rows)}\n")
        out.append(f"### Decode throughput (tok/s, {CANONICAL_KV} KV)\n")
        out.append(fmt_table(rows, "decode_tok_s", CANONICAL_KV) + "\n")
        out.append(f"### Prefill throughput (tok/s, {CANONICAL_KV} KV)\n")
        out.append(fmt_table(rows, "prefill_tok_s", CANONICAL_KV) + "\n")
        # Capability, only if any KLD landed
        if any(r.get("kld") is not None for r in rows):
            out.append(f"### Quality — mean KLD vs q8f16 ({CANONICAL_KV} KV, lower is better)\n")
            out.append(fmt_table(rows, "kld", CANONICAL_KV) + "\n")
        # Format-load failures worth surfacing
        fails = sorted({(r["model"], r["format"]) for r in rows
                        if r.get("status") != "ok" and r.get("kv") == CANONICAL_KV})
        if fails:
            notes = {}
            for r in rows:
                if r.get("status") != "ok" and r.get("kv") == CANONICAL_KV and r.get("note"):
                    notes.setdefault((r["model"], r["format"]), r["note"])
            out.append("<details><summary>Cells that don't load at " + CANONICAL_KV + " KV</summary>\n")
            for (m, f) in fails:
                out.append(f"- `{m}` `{f}`: {notes.get((m, f), 'fault')}")
            out.append("\n</details>\n")

    # Cross-system comparison (only when >1 system)
    if len(systems) > 1:
        out.append("## Cross-system — decode tok/s, mq4 @ q8 KV\n")
        all_models = []
        for s in systems:
            for m in model_order(s["rows"]):
                if m not in all_models:
                    all_models.append(m)
        hdr = "| Model | " + " | ".join(s["name"] for s in systems) + " |\n"
        hdr += "|---|" + "--:|" * len(systems) + "\n"
        lines = []
        pivs = [pivot(s["rows"], "decode_tok_s", CANONICAL_KV) for s in systems]
        for m in all_models:
            cells = [f"{p.get((m, 'mq4')):.0f}" if p.get((m, "mq4")) is not None else "" for p in pivs]
            if any(cells):
                lines.append(f"| {m} | " + " | ".join(cells) + " |")
        out.append(hdr + "\n".join(lines) + "\n")

    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(REPO / "BENCHMARKS.md"))
    args = ap.parse_args()
    systems = load_systems()
    Path(args.out).write_text(render(systems))
    nok = sum(sum(1 for r in s["rows"] if r.get("status") == "ok") for s in systems)
    print(f"wrote {args.out}: {len(systems)} system(s), {nok} working cells")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
